async function main() {
  const sb = getSupabase();

  // Очищаем таблицу (идемпотентно при перезапуске)
  await sb.from('marathon_messages').delete().gte('id', 0);

  for (const msg of MESSAGES) {
    const { error } = await sb.from('marathon_messages').insert({
      step_order: msg.step_order,
      text: msg.text,
      media_type: msg.media_type ?? null,
      media_file_id: msg.media_file_id ?? null,
      button_text: msg.button_text ?? null,
      button_url: msg.button_url ?? null,
      offset_base: msg.offset_base,
      offset_seconds: msg.offset_seconds,
      min_points: msg.min_points ?? null,
      max_points: msg.max_points ?? null,
    });
    if (error) {
      console.error(`step=${msg.step_order} ERROR:`, error.message);
    } else {
      console.log(`step=${msg.step_order} ✅`);
    }
  }
  console.log('\nГотово — всего писем:', MESSAGES.length);
}

main().catch((e) => { console.error(e); process.exit(1); });
